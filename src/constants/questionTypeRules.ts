/**
 * 标签题型判断规则。
 *
 * 数据来源：需求方《题型判断关键词》表（73 条），字段含义：
 * - label     题型标签（与后端题型字典 atd_dic_question_type.typeName 对齐，用于反查 typeCode）
 * - subjects  适用学科；null 表示全学科（学科名见 SUBJECT_CODE_NAME）
 * - keywords  判断关键词（人工校订，保证可做子串匹配）
 * - stems     典型题干标志（原表整句，命中权重高于关键词）
 * - note      备注/易混提示
 *
 * 顺序即需求方表的「序号」，命中分值相同时按此顺序取先者。
 */
